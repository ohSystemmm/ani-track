package services

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

func Convert(outputPath string) error {
	entries, err := LoadEntries()
	if err != nil {
		return fmt.Errorf("error reading entries: %w", err)
	}

	outputPath = strings.TrimSpace(outputPath)
	if outputPath == "" {
		outputPath = "Ani-Track.txt"
	}

	resolvedPath, err := ResolveDirectory(outputPath)
	if err != nil {
		return fmt.Errorf("error resolving directory: %w", err)
	}

	targetFile := resolvedPath
	fi, err := os.Stat(resolvedPath)
	if (err == nil && fi.IsDir()) || strings.HasSuffix(outputPath, "/") || strings.HasSuffix(outputPath, "\\") {
		if err := os.MkdirAll(resolvedPath, 0755); err != nil {
			return err
		}
		targetFile = filepath.Join(resolvedPath, "Ani-Track.txt")
	}

	if err := os.MkdirAll(filepath.Dir(targetFile), 0755); err != nil {
		return fmt.Errorf("error creating directories: %w", err)
	}

	outFile, err := os.Create(targetFile)
	if err != nil {
		return fmt.Errorf("error creating output file %s: %w", targetFile, err)
	}
	defer outFile.Close()

	headerBytes, err := os.ReadFile("assets/Header.txt")
	if err == nil && len(headerBytes) > 0 {
		outFile.Write(headerBytes)
		outFile.WriteString("\n")
	} else {
		outFile.WriteString("========================================================================\n")
		outFile.WriteString("                        A N I - T R A C K                               \n")
		outFile.WriteString("========================================================================\n")
	}

	var history, watchlist []Entry
	for _, e := range entries {
		if e.IsFinished() {
			history = append(history, e)
		} else {
			watchlist = append(watchlist, e)
		}
	}

	fmt.Fprintf(outFile, "Exported: %s\n", time.Now().Format("2006-01-02 15:04:05"))
	fmt.Fprintf(outFile, "Total Entries: %d  |  Watched/Read: %d  |  In Progress/Plan: %d\n\n",
		len(entries), len(history), len(watchlist))

	fmt.Fprintln(outFile, "====================== WATCH HISTORY (Finished) ======================")
	writeFormattedTable(outFile, history)

	fmt.Fprintln(outFile, "\n==================== WATCH LIST (Ongoing / Planned) ====================")
	writeFormattedTable(outFile, watchlist)

	fmt.Fprintln(outFile, "\nGenerated by Ani-Track. Keep tracking!")
	return nil
}

func writeFormattedTable(outFile *os.File, items []Entry) {
	if len(items) == 0 {
		fmt.Fprintln(outFile, "  (No entries in this list)")
		return
	}

	fmt.Fprintf(outFile, "%-4s %-26s %-9s %-8s %-12s %-12s %-12s %-10s %s\n",
		"ID", "Title", "Type", "Rating", "Started", "Finished", "Status", "Progress", "Notes")
	fmt.Fprintln(outFile, strings.Repeat("-", 125))

	for _, e := range items {
		fmt.Fprintf(outFile, "%-4d %-26s %-9s %-8s %-12s %-12s %-12s %-10s %s\n",
			e.Index,
			truncate(e.Title, 26),
			truncate(e.Category, 9),
			truncate(e.Rating, 8),
			truncate(e.Started, 12),
			truncate(e.Finished, 12),
			truncate(e.Status, 12),
			truncate(e.Progress, 10),
			e.Notes)
	}
}

func truncate(s string, maxLen int) string {
	s = strings.TrimSpace(s)
	if len(s) > maxLen {
		if maxLen > 3 {
			return s[:maxLen-3] + "..."
		}
		return s[:maxLen]
	}
	return s
}
